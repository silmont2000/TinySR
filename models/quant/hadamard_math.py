_HADAMARD_BY_K = {12: _HADAMARD_12, 36: _HADAMARD_36}

# Supported lhs_k in decreasing order
_LHS_CANDIDATES = [172, 156, 140, 108, 60, 52, 36, 28, 40, 20, 12]


def _get_hadamard_k(k: int) -> torch.Tensor:
    if is_pow2(k):
        _require_scipy()
        return torch.tensor(scipy.linalg.hadamard(k), dtype=torch.float64)
    if k not in _HADAMARD_BY_K:
        raise ValueError(
            f"No hardcoded Hadamard matrix for k={k}. "
            f"Available: {sorted(_HADAMARD_BY_K.keys())}"
        )
    return _HADAMARD_BY_K[k]


def _get_hadamard_lhs(n: int) -> tuple[torch.Tensor, int]:
    """Find largest supported lhs_k divisor. Returns (lhs_matrix, lhs_k)."""
    for k in _LHS_CANDIDATES:
        if n % k == 0:
            rhs_k = n // k
            assert is_pow2(rhs_k), f"rhs_k={rhs_k} is not power of 2"
            return _get_hadamard_k(k), k
    assert is_pow2(n), (
        f"Size {n} is not supported for Hadamard decomposition. "
        f"Must be power-of-2 or divisible by one of {_LHS_CANDIDATES} "
        f"with power-of-2 quotient."
    )
    return torch.eye(1, dtype=torch.float64), 1


def get_hadamard_matrices(
    n: int,
    scale: bool = True,
    dtype: torch.dtype = torch.float32,
    device: torch.device | str = "cpu",
) -> tuple[torch.Tensor, torch.Tensor, int]:
    """Get RHS, LHS, lhs_k for a given input size n.

    Decompose n = lhs_k * rhs_k where rhs_k is a power of 2 and lhs_k
    uses a hardcoded Hadamard matrix.

    Returns
    -------
    rhs: (rhs_k, rhs_k) power-of-2 Hadamard, scaled by 1/sqrt(n) if scale=True
    lhs: (lhs_k, lhs_k) Hadamard matrix
    lhs_k: int
    """
    device = torch.device(device)
    lhs, k = _get_hadamard_lhs(n)  # internally calls _require_scipy if k is pow2
    rhs_k = n // k
    _require_scipy()
    rhs = torch.tensor(scipy.linalg.hadamard(rhs_k), dtype=torch.float64)
    if scale:
        rhs = rhs.mul_(1.0 / torch.tensor(float(n), dtype=torch.float64).sqrt())
    return rhs.to(dtype=dtype, device=device), lhs.to(dtype=dtype, device=device), k


def hardmard_transform(
    x: torch.Tensor,
    hadamard_rhs: torch.Tensor,
    hadamard_lhs: torch.Tensor | None,
    lhs_k: int,
    scaled: bool = False,
) -> torch.Tensor:
    """Apply structured Walsh-Hadamard rotation to tensor x.

    x: (*, n) input tensor
    hadamard_rhs: (rhs_k, rhs_k) RHS Hadamard matrix
    hadamard_lhs: (lhs_k, lhs_k) LHS Hadamard, or None if lhs_k == 1
    lhs_k: LHS dimension
    scaled: if True, hadamard_rhs is pre-scaled by 1/sqrt(n)
    """
    shape = x.shape
    n = shape[-1]
    rhs_k = n // lhs_k
    x = x.view(-1, lhs_k, rhs_k)
    x = x @ hadamard_rhs
    if not scaled:
        x = x.mul_(
            (1.0 / torch.tensor(float(n), dtype=torch.float64).sqrt()).to(
                device=x.device, dtype=x.dtype
            )
        )
    if lhs_k > 1:
        x = hadamard_lhs @ x
    return x.view(shape)
